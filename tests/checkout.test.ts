import test from "node:test";
import assert from "node:assert/strict";
import { randomBytes, randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import webpush from "web-push";

const url=process.env.HPP_TEST_DATABASE_URL;
test("Direct checkout: price snapshot, emails, payment, grants, reversal",{skip:!url},async()=>{
  const database=new URL(url!);
  assert.ok(["localhost","127.0.0.1"].includes(database.hostname)&&/^\/hpp_test(?:_|$)/.test(database.pathname),"Only a local hpp_test database is allowed.");
  process.env.DATABASE_URL=url;
  process.env.APP_BASE_URL="http://localhost:3000";
  process.env.AUTH_SECRET="local-checkout-test-secret-32-characters-only";
  process.env.META_TRACKING_ENABLED="true";
  process.env.META_PIXEL_ID="123456789012345";
  process.env.META_CAPI_ACCESS_TOKEN="test-token-not-sent-to-meta";
  delete process.env.SMTP_HOST;
  const {auth,activationAuth}=await import("../src/server/auth");
  const {getMigrations}=await import("better-auth/db/migration");
  const {query,getPool,transaction}=await import("../src/server/db");
  const {createCheckoutOrder,findCheckoutOrder,setCheckoutOrderStatus,getCheckoutSettings,orderSchema}=await import("../src/server/checkout");
  const {buildCheckoutEmail}=await import("../src/server/checkout-email");
  const {enqueuePageMetaEvent,purchaseBrowserEvent}=await import("../src/server/meta");
  const paymentRoute=await import("../src/app/api/checkout/orders/[token]/route");
  const {saveMetaSettings,adminMetaSettings,metaConfig}=await import("../src/server/meta-settings");
  const {saveAdminPushSubscription,enqueueOrderPush}=await import("../src/server/admin-push");
  const {adminCustomerSchema,updateAdminCustomer}=await import("../src/server/admin-customer");
  const suffix=randomUUID();
  const email=`checkout-${suffix}@example.test`;
  try{
    await (await getMigrations(auth.options)).runMigrations();
    await query(await readFile(new URL("../db/domain.sql",import.meta.url),"utf8"));
    await query("UPDATE checkout_settings SET enabled=false,price=125000,compare_price=299000,bank_name='',account_number='',account_holder='' WHERE id=1");
    assert.equal((await getCheckoutSettings()).enabled,false);
    const parsed=orderSchema.parse({name:"Pembeli Uji",email,phone:"0812-3456-7890",method:"bank"});
    assert.equal(parsed.phone,"+6281234567890");
    assert.equal(orderSchema.safeParse({name:"Pembeli Uji",email,phone:"12345",method:"bank"}).success,false);
    assert.equal(orderSchema.safeParse({name:"Pembeli Uji",email,method:"bank"}).success,false);
    await assert.rejects(()=>createCheckoutOrder(parsed),{code:"CHECKOUT_CLOSED"});
    await query("UPDATE checkout_settings SET bank_name='Bank Uji',account_number='123456789',account_holder='KulinerKit',enabled=true WHERE id=1");
    const admin=await auth.api.createUser({body:{email:`checkout-admin-${suffix}@example.test`,password:"checkout-admin-password-123",name:"Admin uji",role:"admin"}});
    await query("INSERT INTO user_profile(user_id,account_status,role) VALUES($1,'active','admin')",[admin.user.id]);
    const vapid=webpush.generateVAPIDKeys();
    process.env.PUSH_VAPID_PUBLIC_KEY=vapid.publicKey;
    process.env.PUSH_VAPID_PRIVATE_KEY=vapid.privateKey;
    process.env.PUSH_VAPID_SUBJECT="mailto:admin@example.com";
    await saveAdminPushSubscription(admin.user.id,{endpoint:`https://web.push.apple.com/test-${suffix}`,keys:{p256dh:vapid.publicKey,auth:randomBytes(16).toString("base64url")}});
    assert.equal((await adminMetaSettings()).source,"environment");
    await saveMetaSettings({version:0,enabled:true,pixelId:"123456789012345",graphApiVersion:"v26.0",testEventCode:"TEST-KK",capiToken:"admin-saved-test-token"},admin.user.id);
    const adminSettings=await adminMetaSettings();
    assert.equal(adminSettings.source,"admin");
    assert.equal(adminSettings.active,true);
    assert.equal(adminSettings.hasToken,true);
    assert.equal(adminSettings.testEventCode,"TEST-KK");
    assert.doesNotMatch(JSON.stringify(adminSettings),/admin-saved-test-token/);
    assert.equal((await metaConfig()).token,"admin-saved-test-token");
    assert.notEqual((await query("SELECT capi_token_ciphertext FROM meta_settings WHERE id=1")).rows[0].capi_token_ciphertext,"admin-saved-test-token");
    await assert.rejects(()=>saveMetaSettings({version:0,enabled:false,pixelId:"123456789012345",graphApiVersion:"v26.0",testEventCode:""},admin.user.id),{code:"META_SETTINGS_CHANGED"});
    const result=await createCheckoutOrder(parsed,{client_ip_address:"203.0.113.10",client_user_agent:"Checkout test",fbp:"fb.1.1234567890123.123456"});
    const token=result.url.split("/").at(-1)!;
    assert.match(result.code,/^KK-[A-F0-9]{12}$/);
    const order=await findCheckoutOrder(token);
    assert.equal(order.price,125000);assert.equal(order.compare_price,299000);
    assert.equal(order.customer_phone,"+6281234567890");
    assert.equal(order.payment_snapshot.accountNumber,"123456789");
    assert.equal(order.status,"pending");
    const idResult=await query("SELECT id,token_hash,version FROM checkout_order WHERE code=$1",[result.code]);
    const id=idResult.rows[0].id as string;
    assert.equal((await query("SELECT count(*)::int n FROM admin_push_job WHERE order_id=$1",[id])).rows[0].n,1);
    await transaction(async client=>enqueueOrderPush(client,id));
    assert.equal((await query("SELECT count(*)::int n FROM admin_push_job WHERE order_id=$1",[id])).rows[0].n,1);
    assert.notEqual(idResult.rows[0].token_hash,token);
    assert.equal(await purchaseBrowserEvent(id),null);
    const pendingBody=await (await paymentRoute.GET(new Request(result.url),{params:Promise.resolve({token})})).json();
    assert.equal(pendingBody.metaPurchase,null);
    assert.equal("id" in pendingBody,false);
    const jobs=await query("SELECT kind,payload FROM email_outbox WHERE dedup_key LIKE $1",[`checkout:${id}:%`]);
    assert.equal(jobs.rows.filter(row=>row.kind==="checkout_payment").length,1);
    const adminJob=jobs.rows.find(row=>row.kind==="checkout_admin");
    assert.ok(adminJob);
    assert.equal(adminJob.payload.url,"http://localhost:3000/admin/transactions");
    assert.equal(adminJob.payload.phone,"+6281234567890");
    assert.equal(jobs.rows[0].payload.price,125000);
    const mail=buildCheckoutEmail("checkout_payment",{code:result.code,name:"Pembeli Uji",method:"bank",price:125000,url:result.url});
    assert.match(mail.html,/125\.000/);assert.match(mail.text,/Transfer bank/);
    await query("UPDATE checkout_settings SET price=150000,compare_price=300000 WHERE id=1");
    assert.equal((await findCheckoutOrder(token)).price,125000);
    await assert.rejects(()=>setCheckoutOrderStatus(id,"complete",2,"admin-test","Dana diterima"),{code:"ORDER_CHANGED"});
    await setCheckoutOrderStatus(id,"complete",1,"admin-test","Dana diterima");
    const grants=await query("SELECT feature_key,status,source FROM access_grant WHERE purchase_id=$1 ORDER BY feature_key",[id]);
    assert.deepEqual(grants.rows.map(row=>row.feature_key),["hpp_calculator","prompt_gallery"]);
    assert.ok(grants.rows.every(row=>row.status==="active"&&row.source==="kulinerkit_direct"));
    assert.equal((await findCheckoutOrder(token)).status,"complete");
    let meta=await query("SELECT event_id,status,payload FROM meta_event_outbox WHERE order_id=$1",[id]);
    assert.equal(meta.rows.length,1);
    assert.equal(meta.rows[0].status,"pending");
    assert.equal(meta.rows[0].payload.event_name,"Purchase");
    assert.equal(meta.rows[0].payload.custom_data.value,125000);
    assert.equal(meta.rows[0].payload.user_data.client_ip_address,"203.0.113.10");
    assert.notEqual(meta.rows[0].payload.user_data.em,email);
    assert.deepEqual(await purchaseBrowserEvent(id),{eventId:meta.rows[0].event_id,pixelId:"123456789012345"});
    const completeBody=await (await paymentRoute.GET(new Request(result.url),{params:Promise.resolve({token})})).json();
    assert.deepEqual(completeBody.metaPurchase,{eventId:meta.rows[0].event_id,pixelId:"123456789012345"});
    assert.equal("id" in completeBody,false);
    assert.equal((await query("SELECT count(*)::int n FROM email_outbox WHERE user_id IS NOT NULL AND kind='activation_request' AND dedup_key LIKE $1",[`checkout:${id}:%`])).rows[0].n,1);
    const buyer=(await query("SELECT user_id FROM checkout_order WHERE id=$1",[id])).rows[0].user_id;
    await query("INSERT INTO access_grant(user_id,source,purchase_id,item_id,product_id,feature_key,status) VALUES($1,'lrmobileid-test',$2,'item','product','hpp_calculator','active')",[buyer,`lr-${suffix}`]);
    await setCheckoutOrderStatus(id,"failed",2,"admin-test","Pembayaran dibatalkan");
    assert.equal((await query("SELECT count(*)::int n FROM access_grant WHERE purchase_id=$1 AND status='active'",[id])).rows[0].n,0);
    assert.equal((await query("SELECT status FROM access_grant WHERE purchase_id=$1",[`lr-${suffix}`])).rows[0].status,"active");
    meta=await query("SELECT event_id,status,payload FROM meta_event_outbox WHERE order_id=$1",[id]);
    assert.equal(meta.rows[0].status,"cancelled");
    assert.equal(meta.rows[0].payload,null);
    assert.equal(await purchaseBrowserEvent(id),null);
    await activationAuth.api.requestPasswordReset({body:{email,redirectTo:"http://localhost:3000/activate"}});
    assert.ok((await query("SELECT count(*)::int n FROM verification WHERE value=$1 AND identifier LIKE 'reset-password:%'",[buyer])).rows[0].n>0);
    const correctedEmail=`corrected-${suffix}@example.test`;
    const customerEdit=adminCustomerSchema.parse({id:buyer,name:"Pembeli Terkoreksi",email:correctedEmail,phone:"0813-4567-8901",reason:"Data checkout salah ketik"});
    await assert.rejects(()=>updateAdminCustomer({...customerEdit,email:admin.user.email},admin.user.id),{code:"EMAIL_IN_USE"});
    await assert.rejects(()=>updateAdminCustomer({...customerEdit,id:admin.user.id},admin.user.id),{code:"CUSTOMER_NOT_FOUND"});
    await updateAdminCustomer(customerEdit,admin.user.id);
    assert.deepEqual((await query('SELECT u.email,u.name,u."emailVerified",p.display_name,p.phone FROM "user" u JOIN user_profile p ON p.user_id=u.id WHERE u.id=$1',[buyer])).rows[0],
      {email:correctedEmail,name:"Pembeli Terkoreksi",emailVerified:false,display_name:"Pembeli Terkoreksi",phone:"+6281345678901"});
    assert.equal((await query("SELECT count(*)::int n FROM email_outbox WHERE user_id=$1 AND kind='activation_request' AND recipient=$2 AND status='cancelled'",[buyer,email])).rows[0].n,1);
    assert.equal((await query("SELECT count(*)::int n FROM email_outbox WHERE user_id=$1 AND kind='activation_request' AND recipient=$2 AND status='pending'",[buyer,correctedEmail])).rows[0].n,1);
    assert.equal((await query("SELECT count(*)::int n FROM verification WHERE value=$1 AND identifier LIKE 'reset-password:%'",[buyer])).rows[0].n,0);
    assert.equal((await query("SELECT count(*)::int n FROM account_token WHERE user_id=$1 AND kind='activation' AND revoked_at IS NOT NULL",[buyer])).rows[0].n,1);
    assert.equal((await query("SELECT count(*)::int n FROM audit_log WHERE actor_id=$1 AND action='edit_customer' AND target=$2",[admin.user.id,buyer])).rows[0].n,1);
    await setCheckoutOrderStatus(id,"complete",3,"admin-test","Dana diterima ulang");
    assert.equal((await query("SELECT user_id FROM checkout_order WHERE id=$1",[id])).rows[0].user_id,buyer);
    assert.equal((await query("SELECT recipient FROM email_outbox WHERE dedup_key=$1",[`checkout:${id}:activation_request:4`])).rows[0].recipient,correctedEmail);
    meta=await query("SELECT event_id,status,payload FROM meta_event_outbox WHERE order_id=$1",[id]);
    assert.equal(meta.rows.length,1);
    assert.equal(meta.rows[0].status,"pending");
    // Transport is tested with a fake HTTPS request in meta-transport.test.ts.
    // Keep this integration test offline; replacing settings cancels queued events.
    await assert.rejects(()=>setCheckoutOrderStatus(id,"complete",4,"admin-test","Ulang"),{code:"STATUS_UNCHANGED"});
    const pageEventId=randomUUID();
    await enqueuePageMetaEvent("ViewContent",pageEventId,125000,new Request("http://localhost:3000/",{headers:{"user-agent":"Meta test"}}));
    assert.equal((await query("SELECT status,pixel_id FROM meta_event_outbox WHERE event_id=$1",[pageEventId])).rows[0].status,"pending");
    await saveMetaSettings({version:1,enabled:true,pixelId:"987654321012345",graphApiVersion:"v26.0",testEventCode:"",capiToken:"replacement-test-token"},admin.user.id);
    assert.equal((await query("SELECT status,payload FROM meta_event_outbox WHERE order_id=$1",[id])).rows[0].status,"cancelled");
    assert.equal((await query("SELECT status,payload FROM meta_event_outbox WHERE order_id=$1",[id])).rows[0].payload,null);
    assert.equal((await query("SELECT status,payload FROM meta_event_outbox WHERE event_id=$1",[pageEventId])).rows[0].status,"cancelled");
    assert.equal((await query("SELECT status,payload FROM meta_event_outbox WHERE event_id=$1",[pageEventId])).rows[0].payload,null);
    assert.equal((await metaConfig()).pixelId,"987654321012345");
    assert.equal(await purchaseBrowserEvent(id),null);
  }finally{await getPool().end();}
});
