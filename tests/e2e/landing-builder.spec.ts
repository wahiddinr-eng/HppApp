import { expect, test } from "@playwright/test";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";

test.skip(!process.env.HPP_TEST_DATABASE_URL, "A local hpp_test database is required.");

test("admin can draft, preview, and publish a landing page with an HTML anchor", async ({ page }) => {
  const dbUrl = new URL(process.env.HPP_TEST_DATABASE_URL!);
  expect(["localhost", "127.0.0.1"]).toContain(dbUrl.hostname);
  expect(dbUrl.pathname).toMatch(/^\/hpp_test(?:_|$)/);
  const { auth } = await import("../../src/server/auth");
  const { getMigrations } = await import("better-auth/db/migration");
  const { query } = await import("../../src/server/db");
  await (await getMigrations(auth.options)).runMigrations();
  await query(await readFile(new URL("../../db/domain.sql", import.meta.url), "utf8"));
  const suffix = randomUUID();
  const email = `landing-browser-${suffix}@example.test`;
  const password = "landing-browser-password-123";
  const slug = `landing-${suffix}`;
  const admin = await auth.api.createUser({ body: { email, password, name: "Admin landing", role: "admin" } });
  await query("INSERT INTO user_profile(user_id,account_status,role) VALUES($1,'active','admin')", [admin.user.id]);

  await page.goto("/login");
  await page.getByLabel("Alamat email").fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto("/admin/landing-pages");
  let previewMetaRequests = 0;
  page.on("request", request => { if (request.url().includes("/api/meta/events")) previewMetaRequests++; });
  await page.getByRole("button", { name: "Buat landing page" }).click();
  await page.getByLabel("Judul halaman").fill("Landing browser uji");
  const livePreview = page.getByRole("complementary", { name: "Pratinjau langsung" });
  await expect(livePreview).toContainText("Landing browser uji");
  await expect(livePreview.locator("[data-preview-device]")).toHaveAttribute("data-preview-device", "desktop");
  await expect(livePreview.locator('[data-landing-renderer]').first()).toBeVisible();
  const heading = livePreview.locator("h1");
  await expect.poll(() => heading.evaluate(element => getComputedStyle(element).fontSize)).toBe("76px");
  await livePreview.getByRole("button", { name: "Mobile" }).click();
  await expect(livePreview.locator("[data-preview-device]")).toHaveAttribute("data-preview-device", "mobile");
  await expect(livePreview.locator('[data-landing-renderer]').first()).toBeVisible();
  await expect.poll(() => heading.evaluate(element => getComputedStyle(element).fontSize)).toBe("44px");
  await livePreview.getByRole("button", { name: "Desktop" }).click();
  await page.getByLabel("Slug URL").fill(slug);
  await page.getByRole("checkbox", { name: /Aktifkan ViewContent/ }).check();
  expect(previewMetaRequests).toBe(0);
  await page.locator("select").selectOption("CUSTOM_HTML");
  await page.getByRole("button", { name: "Tambah blok" }).click();
  await page.getByLabel("HTML, CSS, dan JavaScript").fill('<div style="padding:30px;height:800px"><a href="#manfaat">Lihat manfaat</a></div>');
  await expect(livePreview.frameLocator("iframe").getByText("Lihat manfaat")).toBeVisible();
  await page.getByRole("button", { name: "Simpan draft" }).click();
  await expect(page.getByRole("status")).toContainText("Draft tersimpan");
  await expect(page.getByRole("checkbox", { name: /Aktifkan ViewContent/ })).toBeChecked();
  expect((await page.request.get(`/landing/${slug}`)).status()).toBe(404);
  const preview = page.getByRole("link", { name: "Pratinjau tersimpan" });
  await expect(preview).toHaveAttribute("href", /\/landing\/preview\/[0-9a-f-]+$/);
  const previewUrl = await preview.getAttribute("href");
  await page.goto(previewUrl!);
  await expect(page.getByText("Pratinjau admin")).toBeVisible();
  await expect(page.frameLocator("iframe").getByText("Lihat manfaat")).toBeVisible();
  await page.goto("/admin/landing-pages");
  await page.getByRole("button", { name: new RegExp(slug) }).click();
  await page.getByRole("button", { name: "Terbitkan" }).click();
  await expect(page.getByRole("status")).toContainText("diterbitkan");
  await page.goto(`/landing/${slug}`);
  await expect(page.frameLocator("iframe").getByText("Lihat manfaat")).toBeVisible();
  await page.evaluate(() => { (window as Window & { landingMarker?: string }).landingMarker = "kept"; });
  await page.frameLocator("iframe").getByText("Lihat manfaat").click();
  await expect.poll(() => page.evaluate(() => location.hash)).toBe("#manfaat");
  await expect.poll(() => page.evaluate(() => { const rect = document.getElementById("manfaat")?.getBoundingClientRect(); return Boolean(rect && rect.top < innerHeight && rect.bottom > 0); })).toBe(true);
  expect(await page.evaluate(() => (window as Window & { landingMarker?: string }).landingMarker)).toBe("kept");
});
